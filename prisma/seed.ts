async function main() {
  for (const category of categories) {
    const saved = await prisma.category.upsert({
      where: { slug: category.slug },
      update: { name: category.name, icon: category.icon, sortOrder: category.sortOrder, status: RecordStatus.ACTIVE },
      create: { name: category.name, slug: category.slug, icon: category.icon, sortOrder: category.sortOrder }
    });

    const extras = extraWords[category.slug] ?? { easy: [], medium: [], hard: [] };
    const groups = [
      { words: [...category.easy, ...extras.easy], points: 2, difficulty: Difficulty.EASY },
      { words: [...category.medium, ...extras.medium], points: 4, difficulty: Difficulty.MEDIUM },
      { words: [...category.hard, ...extras.hard], points: 6, difficulty: Difficulty.HARD }
    ];

    for (const group of groups) {
      for (const title of group.words) {
        const existing = await prisma.word.findFirst({ where: { title, categoryId: saved.id } });
        if (!existing) {
          await prisma.word.create({
            data: { title, categoryId: saved.id, points: group.points, difficulty: group.difficulty }
          });
        }
      }
    }
  }

  await prisma.setting.upsert({
    where: { key: "product_name" },
    update: { value: "ادازی" },
    create: { key: "product_name", value: "ادازی" }
  });

  console.log(`Seed complete: ${categories.length} categories, expanded word pool`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
